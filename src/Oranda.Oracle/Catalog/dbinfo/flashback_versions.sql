SELECT VERSIONS_STARTTIME, VERSIONS_ENDTIME, VERSIONS_OPERATION, RAWTOHEX(VERSIONS_XID) AS VERSIONS_XID, @COLUMNS@
FROM @TABLE@ VERSIONS BETWEEN @RANGE@ AND MAXVALUE
WHERE @CONDITIONS@
ORDER BY VERSIONS_STARTSCN DESC NULLS LAST
