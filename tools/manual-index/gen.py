#!/usr/bin/env python3
"""매뉴얼 색인 생성기: site/src/content/docs 의 머리말(title·description)과 h2 제목으로 OrandaManual 색인 표(C# 소스)를 만든다.

쓰는 법(리포 루트에서):
    python3 tools/manual-index/gen.py            # src/Oranda.Core/Ai/Manual/OrandaManualIndex.cs 를 다시 쓴다
    python3 tools/manual-index/gen.py --check    # 다시 만든 글이 파일과 다르면 종료 1(고치지 않음)
    python3 tools/manual-index/gen.py --out F    # 다른 곳에 쓴다

규칙(Agent.Cli.Tests 의 맞춤 시험이 같은 규칙으로 site/ 와 표를 견준다):
- 주소 = https://jongik-sv.github.io/oranda/<경로>/ (astro.config.mjs 의 site + base). 경로 = docs 아래 파일 경로에서 확장자를 뺀 값,
  끝이 index 면 그 폴더(manual/index.mdx → manual/).
- draft: true 인 쪽은 넣지 않는다(게시 빌드에서 빠진다).
- 장(Section) = docs 아래 첫 폴더 이름(run·plan·ai…, 계약 §8.5).
- h2 = 코드 블록 밖의 '## ' 줄(글 그대로). docs 검색에만 쓴다(E-28).
- 순서 = 사이드바 순서(사이드바에 없는 폴더는 뒤), 같은 장 안에서는 sidebar.order(없으면 뒤) → 파일 경로.
"""
import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(REPO, "site", "src", "content", "docs")
CONFIG = os.path.join(REPO, "site", "astro.config.mjs")
DEFAULT_OUT = os.path.join(REPO, "src", "Oranda.Core", "Ai", "Manual", "OrandaManualIndex.cs")


def site_root():
    text = open(CONFIG, encoding="utf-8").read()
    site = re.search(r"site:\s*'([^']+)'", text).group(1)
    base = re.search(r"base:\s*'([^']+)'", text).group(1)
    return site.rstrip("/") + "/" + base.strip("/")


def sidebar():
    """폴더 → 사이드바 순서."""
    text = open(CONFIG, encoding="utf-8").read()
    groups = re.findall(r"label:\s*'([^']+)',\s*items:\s*\[\{\s*autogenerate:\s*\{\s*directory:\s*'([^']+)'", text)
    return {directory: i for i, (_, directory) in enumerate(groups)}


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        inner = value[1:-1]
        return inner.replace("''", "'") if value[0] == "'" else inner.replace('\\"', '"')
    return value


def parse(path):
    lines = open(path, encoding="utf-8").read().replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        raise SystemExit(f"머리말이 없다: {path}")
    meta, order, i = {}, None, 1
    in_sidebar = False
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        top = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if top:
            key, value = top.group(1), top.group(2)
            in_sidebar = key == "sidebar"
            if key in ("title", "description", "draft"):
                if value.strip() in (">", "|", ">-", "|-"):
                    raise SystemExit(f"여러 줄 머리말 값은 지원하지 않는다: {path} {key}")
                meta[key] = unquote(value)
        elif in_sidebar:
            m = re.match(r"^\s+order:\s*(-?\d+)\s*$", line)
            if m:
                order = int(m.group(1))
        i += 1
    # 코드 블록(CommonMark): 같은 글자 3개 이상으로 열고, 같은 글자를 그 이상 늘어놓은 빈 줄로 닫는다(````markdown 안의 ```sql 은 닫지 않는다).
    headings, fence = [], None
    for line in lines[i + 1:]:
        m = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line)
        if m:
            run, rest = m.group(1), m.group(2)
            if fence is None:
                fence = run
            elif run[0] == fence[0] and len(run) >= len(fence) and rest.strip() == "":
                fence = None
            continue
        if fence is None and line.startswith("## "):
            headings.append(line[3:].strip())
    return meta, order, headings


def entries():
    root, groups = site_root(), sidebar()
    result = []
    for folder, _, files in os.walk(DOCS):
        for name in files:
            if not name.endswith((".md", ".mdx")):
                continue
            path = os.path.join(folder, name)
            meta, order, headings = parse(path)
            if meta.get("draft", "").lower() == "true":
                continue
            rel = os.path.relpath(path, DOCS).replace(os.sep, "/")
            slug = re.sub(r"\.mdx?$", "", rel)
            slug = re.sub(r"(^|/)index$", "", slug)
            section = rel.split("/")[0] if "/" in rel else ""
            group_order = groups.get(section, len(groups))
            url = root + "/" + (slug + "/" if slug else "")
            result.append(((group_order, order if order is not None else 1_000_000, rel),
                           meta["title"], meta.get("description", ""), url, section, headings))
    result.sort(key=lambda e: e[0])
    return [e[1:] for e in result]


def cs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    out = [
        "// <auto-generated>",
        "// tools/manual-index/gen.py 가 site/src/content/docs 에서 만든다. 손으로 고치지 않는다.",
        "// 본문 머리말·h2 를 바꾸면 리포 루트에서 python3 tools/manual-index/gen.py 를 다시 돌린다.",
        "// </auto-generated>",
        "#nullable enable",
        "",
        "namespace Oranda.Core.Ai.Manual;",
        "",
        "public static partial class OrandaManual",
        "{",
        "    private static readonly Entry[] Generated =",
        "    [",
    ]
    for title, description, url, section, headings in entries():
        out.append(f"        new({cs(title)}, {cs(description)}, {cs(url)}, {cs(section)})")
        out.append("        {")
        out.append("            Headings = [" + ", ".join(cs(h) for h in headings) + "],")
        out.append("        },")
    out += ["    ];", "}", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
        if current.replace("\r\n", "\n") != text:
            print(f"색인이 site/ 와 다르다: python3 tools/manual-index/gen.py 로 {os.path.relpath(args.out, REPO)} 를 다시 만든다", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(entries())}쪽 → {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
