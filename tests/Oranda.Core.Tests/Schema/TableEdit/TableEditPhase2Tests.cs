    // ---------- 18.1 테이블 이름 바꾸기 ----------

    [Fact]
    public void Rename_table_is_the_last_statement_without_owner_on_the_new_name()
    {
        var (original, edited) = Start();
        edited = (edited with { Name = "ORDERS_OLD", Comment = "c" }).WithColumn("NOTE", c => c with { Name = "MEMO" });

        var script = TableEditScriptBuilder.Build(original, edited, Dialect);

        Assert.Equal(
            [T + "RENAME COLUMN NOTE TO MEMO", "COMMENT ON TABLE SAMPLE.ORDERS IS 'c'", T + "RENAME TO ORDERS_OLD"],
            script.Texts());
        var rename = script.Statements[^1];
        Assert.Equal((TableEditPage.Description, TableDraft.TableRowKey), (rename.Page, rename.RowKey));
        Assert.Equal(new Oranda.Core.Journal.ChangeTarget("SAMPLE", "ORDERS", "TABLE", Oranda.Core.Journal.ChangeOperation.Alter), rename.Statement.ChangeTarget);
        Assert.True(TableDraftDiff.Compute(original, edited, Dialect).Renamed);
    }

    [Fact]
    public void Rule_names_follow_the_table_only_when_asked()
    {
        // TE-38: 기본은 따라 바꾸지 않음. 켜면 PK_<옛 이름>·IX_<옛 이름>_NN 꼴만 RENAME.
        var (original, edited) = Start();
        var renamed = edited with { Name = "SALES" };

        Assert.Equal([T + "RENAME TO SALES"], Build(original, renamed));
        Assert.Equal(
            [
                T + "RENAME CONSTRAINT PK_ORDERS TO PK_SALES",
                T + "RENAME CONSTRAINT CK_ORDERS_01 TO CK_SALES_01",
                T + "RENAME CONSTRAINT FK_ORDERS_01 TO FK_SALES_01",
                "ALTER INDEX SAMPLE.PK_ORDERS RENAME TO PK_SALES",
                "ALTER INDEX SAMPLE.IX_ORDERS_01 RENAME TO IX_SALES_01",
                "ALTER INDEX SAMPLE.IX_ORDERS_02 RENAME TO IX_SALES_02",
                T + "RENAME TO SALES",
            ],
            Build(original, renamed with { RenameRuleNames = true }));
    }

