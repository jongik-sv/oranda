    // ---------- T13 리뷰 반영 ----------

    private static TableInfo WithSeq(IdentityInfo? identity) => Orders() with
    {
        Columns = [.. Orders().Columns, new ColumnInfo("SEQ", 10, "NUMBER") { IsIdentity = true, Identity = identity, IsNullable = false }],
    };

    [Fact]
    public void Existing_identity_modify_writes_only_the_changed_options()
    {
        // START WITH 를 다시 쓰면 시퀀스가 그 값부터 다시 시작해 키가 겹친다 — 바뀐 옵션만.
        var (original, edited) = Start(WithSeq(new IdentityInfo(IdentityGeneration.ByDefault) { StartWith = 1, IncrementBy = 1 }));

        Assert.Equal([T + "MODIFY (SEQ GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5))"],
            Build(original, edited.WithColumn("SEQ", c => c with { Identity = c.Identity! with { IncrementBy = 5 } })));
        Assert.Equal([T + "MODIFY (SEQ GENERATED ALWAYS AS IDENTITY)"],
            Build(original, edited.WithColumn("SEQ", c => c with { Identity = c.Identity! with { Generation = IdentityGeneration.Always } })));
        Assert.Equal([T + "MODIFY (SEQ GENERATED BY DEFAULT AS IDENTITY (START WITH 1000))"],
            Build(original, edited.WithColumn("SEQ", c => c with { Identity = c.Identity! with { StartWith = 1000 } })));
    }

    [Fact]
    public void Unread_identity_is_not_guessed()
    {
        // 공급자가 신원 속성을 못 읽으면 ALWAYS 로 짐작하지 않는다(BY DEFAULT 열이 ALWAYS 로 바뀌던 결함).
        var table = WithSeq(null);
        var (original, edited) = Start(table);
        var seq = original.Columns.Single(c => c.Name == "SEQ");

        Assert.Equal((null, true, true), (seq.Identity, seq.IsIdentityUnknown, seq.IsIdentityColumn));
        Assert.Empty(Build(original, edited.WithColumn("SEQ", c => c with { Comment = "x" })).Where(s => s.Contains("IDENTITY", StringComparison.Ordinal)));

        var set = edited.WithColumn("SEQ", c => c with { Identity = new IdentityInfo(IdentityGeneration.ByDefault) { IncrementBy = 2 }, IsIdentityUnknown = false });
        Assert.Single(TableEditCheckPlanner.Plan(original, set, Dialect, Dev).Findings,
            f => f is { Severity: CheckSeverity.Block, Code: CheckCode.InvalidDefinition, Detail: "identityUnknown" });

        var drop = edited.WithColumn("SEQ", c => c with { IsIdentityUnknown = false });
        Assert.Equal([T + "MODIFY (SEQ DROP IDENTITY)"], Build(original, drop));
        Assert.DoesNotContain(TableEditCheckPlanner.Plan(original, drop, Dialect, Dev).Findings, f => f.Severity == CheckSeverity.Block);

        var copy = TableDraftFactory.CopyStructure(table, "SAMPLE", "ORDERS_BAK", Dialect, 30).Columns.Single(c => c.Name == "SEQ");
        Assert.Equal((null, false), (copy.Identity, copy.IsIdentityUnknown));
    }

