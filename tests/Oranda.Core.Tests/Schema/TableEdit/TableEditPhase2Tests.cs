    [Fact]
    public void Rule_rename_skips_the_index_of_a_dropped_primary_key()
    {
        // PK 를 지우면 그 인덱스도 사라진다 — 없는 인덱스를 ALTER INDEX … RENAME 하면 ORA-01418.
        var (original, edited) = Start();
        edited = edited.WithConstraint("PK_ORDERS", c => c with { IsDropped = true }) with { Name = "SALES", RenameRuleNames = true };

        var texts = Build(original, edited);

        Assert.DoesNotContain(texts, s => s.Contains("PK_ORDERS RENAME", StringComparison.Ordinal) || s.Contains("PK_SALES", StringComparison.Ordinal));
        Assert.Contains("ALTER INDEX SAMPLE.IX_ORDERS_01 RENAME TO IX_SALES_01", texts);
        Assert.Equal(T + "RENAME TO SALES", texts[^1]);
    }

    [Fact]
    public void Rule_rename_then_failed_table_rename_does_not_rename_back()
    {
        // 규칙 이름 바꾸기 6개 성공 + RENAME TO 실패 → 다시 계산하면 RENAME TO 만 남는다(되돌리는 RENAME CONSTRAINT 없음).
        var (original, edited) = Start();
        edited = edited with { Name = "SALES", RenameRuleNames = true };
        var script = TableEditScriptBuilder.Build(original, edited, Dialect);
        Assert.Equal(7, script.Statements.Count);

        static string Swap(string n) => n.Replace("_ORDERS", "_SALES", StringComparison.Ordinal);
        var server = Orders() with
        {
            Constraints = [.. Orders().Constraints.Select(c => c with { Name = Swap(c.Name) })],
            Indexes = [.. Orders().Indexes.Select(i => i with { Name = Swap(i.Name), ConstraintName = i.ConstraintName is { } k ? Swap(k) : null })],
        };
        var reread = TableDraftFactory.FromTable(server, Dialect);

        Assert.Equal([T + "RENAME TO SALES"], Build(reread, TableDraftRebase.Rebase(original, edited, script, 6, reread)));
    }

    [Fact]
    public void Rule_rename_targets_are_checked_for_clashes()
    {
        var (original, edited) = Start();
        var renamed = edited with { Name = "SALES", RenameRuleNames = true };

        var plan = TableEditCheckPlanner.Plan(original, renamed, Dialect, Dev);
        Assert.Equal(["PK_SALES", "CK_SALES_01", "FK_SALES_01"],
            plan.Checks.Where(c => c is { Kind: TableEditCheckKind.NameExists, NameKind: TableEditNameKind.Constraint }).Select(c => c.Name));
        Assert.Equal(["PK_SALES", "IX_SALES_01", "IX_SALES_02"],
            plan.Checks.Where(c => c is { Kind: TableEditCheckKind.NameExists, NameKind: TableEditNameKind.Index }).Select(c => c.Name));

        var clash = renamed.AddIndex(new IndexDraft("n1", "IX_SALES_01") { Columns = [new IndexColumnDraft(edited.KeyOf("QTY"))] });
        Assert.Contains(TableEditCheckPlanner.Plan(original, clash, Dialect, Dev).Findings,
            f => f is { Severity: CheckSeverity.Block, Code: CheckCode.NameExists, RowKey: "i3", Subject: "IX_SALES_01" });
        Assert.Empty(TableEditCheckPlanner.Plan(original, edited with { Name = "SALES" }, Dialect, Dev).Checks
            .Where(c => c.NameKind is TableEditNameKind.Constraint or TableEditNameKind.Index));
    }

