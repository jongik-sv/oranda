    // ---------- 18.10 GTT·IOT ----------

    private static TableDraft NewTable(TableKind kind) => (TableDraftFactory.Empty("SAMPLE") with { Name = "T1", Kind = kind, Tablespace = "USERS" })
        .AddColumn(new ColumnDraft("c1", "ID") { DataType = "NUMBER", IsNullable = false })
        .AddColumn(new ColumnDraft("c2", "V") { DataType = "VARCHAR2", Length = 10 });

    [Fact]
    public void Global_temporary_table_on_commit_rows()
    {
        Assert.Equal(["CREATE GLOBAL TEMPORARY TABLE SAMPLE.T1 (ID NUMBER NOT NULL, V VARCHAR2(10)) ON COMMIT DELETE ROWS"],
            Build(TableDraftFactory.Empty("SAMPLE"), NewTable(TableKind.Temporary)));
        Assert.Equal(["CREATE GLOBAL TEMPORARY TABLE SAMPLE.T1 (ID NUMBER NOT NULL, V VARCHAR2(10)) ON COMMIT PRESERVE ROWS"],
            Build(TableDraftFactory.Empty("SAMPLE"), NewTable(TableKind.Temporary) with { OnCommitPreserveRows = true }));
    }

    [Fact]
    public void Index_organized_table_needs_a_primary_key()
    {
        var iot = NewTable(TableKind.Iot).AddConstraint(new ConstraintDraft("k1", "PK_T1", ConstraintKind.PrimaryKey) { ColumnKeys = ["c1"] });

        Assert.Equal(["CREATE TABLE SAMPLE.T1 (ID NUMBER NOT NULL, V VARCHAR2(10), CONSTRAINT PK_T1 PRIMARY KEY (ID)) ORGANIZATION INDEX TABLESPACE USERS"],
            Build(TableDraftFactory.Empty("SAMPLE"), iot));
        Assert.Single(TableEditCheckPlanner.Plan(TableDraftFactory.Empty("SAMPLE"), NewTable(TableKind.Iot), Dialect, Dev).Findings,
            f => f is { Severity: CheckSeverity.Block, Code: CheckCode.InvalidDefinition });
    }

    [Fact]
    public void Special_table_creation_follows_the_dialect_support()
