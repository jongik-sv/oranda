    [Fact]
    public void Existing_special_tables_allow_only_comments_defaults_and_column_add_drop()
    {
        var gtt = Orders() with { Kind = TableKind.Temporary };
        var (original, edited) = Start(gtt);
        var allowed = edited.WithColumn("NOTE", c => c with { Comment = "x", DefaultValue = "'-'" }).AddColumn(new ColumnDraft("n1", "CODE") { DataType = "DATE" });
