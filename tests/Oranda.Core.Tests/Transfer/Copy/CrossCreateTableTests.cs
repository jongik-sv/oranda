    [Fact]
    public async Task Create_uses_the_create_blocked_reason_and_recreate_keeps_the_recreate_one()
    {
        // 만들기만 막는 방언: 없으면 만들기는 CreateBlocked, 다시 만들기는 막히지 않는다.
        var create = new Fixture(Dbms.Oracle, Dbms.Tibero, Orders("SRC"), targetDialect: new SplitPrecheckDialect(recreateBlocked: null, createBlocked: "만들기 막힘"));
        var created = await create.PrecheckAsync();
        var blocked = Assert.Single(created.Items, i => i.Code == CopyCheckCodes.CreateBlocked);
        Assert.Equal(CheckLevel.Error, blocked.Level);
        Assert.Contains("만들기 막힘", blocked.Message, StringComparison.Ordinal);

        var recreate = new Fixture(Dbms.Tibero, Dbms.Oracle, Orders("SRC"), action: TargetAction.Recreate, create: false, targetHasTable: true,
            targetDialect: new SplitPrecheckDialect(recreateBlocked: null, createBlocked: "만들기 막힘"));
        var recreated = await recreate.PrecheckAsync();
        Assert.DoesNotContain(recreated.Items, i => i.Code is "RecreateBlocked" or CopyCheckCodes.CreateBlocked);
        Assert.Contains(recreated.Items, i => i.Code == "RecreateTable");
    }

    [Fact]
    public async Task A_target_dialect_recreate_blocked_reason_is_a_precheck_error_only_when_it_is_not_null()
    {
        // Oracle → Tibero 다시 만들기: 대상 방언의 RecreateBlockedReason 이 글이면 RecreateBlocked 오류(D12). Tibero → Oracle 은 방언이 null 이라 막히지 않는다.
        var toTibero = new Fixture(Dbms.Oracle, Dbms.Tibero, Orders("SRC"), action: TargetAction.Recreate, create: false, targetHasTable: true,
