    [Fact]
    public void A_job_fk_to_a_parent_column_or_key_the_parent_map_leaves_out_is_filtered_and_the_precheck_form_agrees()
    {
        var parent = new TableInfo(new DbObjectRef("SRC", "PARENT", "TABLE"),
        [
            new ColumnInfo("ID", 1, "NUMBER") { Precision = 10, Scale = 0, IsNullable = false },
            new ColumnInfo("CODE", 2, "NUMBER") { Precision = 5, Scale = 0, IsNullable = false },
            new ColumnInfo("RID", 3, "ROWID"),
        ])
        {
            Constraints =
            [
                new ConstraintInfo("PK_PARENT", ConstraintKind.PrimaryKey, ["ID"]),
                new ConstraintInfo("UK_PARENT", ConstraintKind.Unique, ["CODE", "RID"]),
            ],
        };
        var fkToId = new ConstraintInfo("FK_ID", ConstraintKind.ForeignKey, ["PID"])
        {
            ReferencedTable = parent.Table,
            ReferencedConstraint = "PK_PARENT",
        };
        var fkToUk = new ConstraintInfo("FK_UK", ConstraintKind.ForeignKey, ["C1", "C2"])
        {
            ReferencedTable = parent.Table,
            ReferencedConstraint = "UK_PARENT",
        };
        var child = new TableInfo(new DbObjectRef("SRC", "CHILD", "TABLE"),
        [
            new ColumnInfo("PID", 1, "NUMBER") { Precision = 10, Scale = 0 },
            new ColumnInfo("C1", 2, "NUMBER") { Precision = 5, Scale = 0 },
            new ColumnInfo("C2", 3, "NUMBER") { Precision = 5, Scale = 0 },
        ])
        {
            Constraints = [fkToId, fkToUk],
        };
        (string, string, string?)[] fks =
        [
            ("PARENT", "ALTER TABLE \"DST\".\"CHILD\" ADD CONSTRAINT \"FK_ID\" FOREIGN KEY (\"PID\") REFERENCES \"DST\".\"PARENT\" (\"ID\")", "FK_ID"),
            ("PARENT", "ALTER TABLE \"DST\".\"CHILD\" ADD FOREIGN KEY (\"C1\", \"C2\") REFERENCES \"DST\".\"PARENT\" (\"CODE\", \"RID\")", null),
        ];

        var (kept, skipped) = CrossTableMap.FilterForeignKeys(Dbms.Oracle, Dbms.Tibero, child, null, fks, name => name == "PARENT" ? parent : null);

        Assert.Equal(["FK_ID"], kept.Select(k => k.Name));
        var only = Assert.Single(skipped);
        Assert.Contains("FK_UK", only, StringComparison.Ordinal); // 이름 없는 FK 도 원본 제약 이름으로 알린다
        Assert.Contains("PARENT", only, StringComparison.Ordinal);

        var precheck = CrossTableMap.SkippedForeignKeys(Dbms.Oracle, Dbms.Tibero, child, null, [fkToId, fkToUk], p => p.Name == "PARENT" ? parent : null);
        var skippedByPrecheck = Assert.Single(precheck);
        Assert.Equal("FK_UK", skippedByPrecheck.Fk.Name);
        Assert.Equal(only, CrossTableMap.FormatSkipped("FK_UK", "PARENT", skippedByPrecheck.Reason));

        // 같은 DBMS 는 아무것도 빼지 않는다.
        Assert.Equal(fks.Length, CrossTableMap.FilterForeignKeys(Dbms.Oracle, Dbms.Oracle, child, null, fks, name => parent).Kept.Count);
        Assert.Empty(CrossTableMap.SkippedForeignKeys(Dbms.Oracle, Dbms.Oracle, child, null, [fkToId, fkToUk], p => parent));
    }

    // ---- 실행기 보호선 (리뷰 4) ----

    [Fact]
    public async Task Runner_refuses_create_and_recreate_when_the_target_dialect_blocks_them_even_with_an_error_free_report()
    {
        // 점검은 막지 않는 방언으로 통과시키고, 실행기에는 막는 방언을 준다: 오류 없는 점검 결과를 넘겨도 실행기가 한 번 더 막는다.
        var create = new Fixture(Dbms.Oracle, Dbms.Tibero, Orders("SRC"), runnerDialect: new SplitPrecheckDialect(recreateBlocked: null, createBlocked: "만들기 막힘"));
        var createReport = await create.PrecheckAsync();
        Assert.False(createReport.HasErrors);
        var createError = await Assert.ThrowsAsync<InvalidOperationException>(() => create.RunAsync(createReport));
        Assert.Contains("만들기 막힘", createError.Message, StringComparison.Ordinal);
        Assert.DoesNotContain(create.Execution.Calls, c => IsCreateText(c.Statement.Text));

        var recreate = new Fixture(Dbms.Oracle, Dbms.Tibero, Orders("SRC"), action: TargetAction.Recreate, create: false, targetHasTable: true,
            runnerDialect: new PrecheckDialect("다시 만들기 막힘"));
        var recreateReport = await recreate.PrecheckAsync();
        Assert.False(recreateReport.HasErrors);
        var recreateError = await Assert.ThrowsAsync<InvalidOperationException>(() => recreate.RunAsync(recreateReport));
        Assert.Contains("다시 만들기 막힘", recreateError.Message, StringComparison.Ordinal);
        Assert.Empty(recreate.Execution.Calls);

        // 막는 이유가 없으면(null) 그대로 실행한다.
        var open = new Fixture(Dbms.Oracle, Dbms.Tibero, Orders("SRC"), runnerDialect: new SplitPrecheckDialect(recreateBlocked: null, createBlocked: null));
        var openReport = await open.PrecheckAsync();
        await open.RunAsync(openReport);
        Assert.Contains(open.Execution.Calls, c => IsCreateText(c.Statement.Text));
    }

