    [Fact]
    public void Oracle_to_tibero_ddl_leaves_out_dropped_virtual_and_identity_parts_and_converts_types()
    {
        var table = new TableInfo(new DbObjectRef("SRC", "T", "TABLE"),
        [
            new ColumnInfo("ID", 1, "NUMBER") { Precision = 10, Scale = 0, IsNullable = false, IsIdentity = true, DefaultValue = "\"SRC\".\"ISEQ$$_1\".nextval" },
            new ColumnInfo("NAME", 2, "VARCHAR2") { Length = 20 },
            new ColumnInfo("RID", 3, "ROWID"),
            new ColumnInfo("V1", 4, "NUMBER") { IsVirtual = true, DefaultValue = "ID*2" },
            new ColumnInfo("BIGRAW", 5, "RAW") { Length = 3000 },
        ])
        {
            Constraints =
            [
                new ConstraintInfo("PK_T", ConstraintKind.PrimaryKey, ["ID"]),
                new ConstraintInfo("CK_RID", ConstraintKind.Check, ["RID"]) { Condition = "RID IS NOT NULL" },
                new ConstraintInfo("CK_NAME", ConstraintKind.Check, ["NAME"]) { Condition = "LENGTH(NAME) > 0" },
            ],
            Indexes = [new IndexInfo("IX_RID", false, ["RID"]), new IndexInfo("IX_NAME", false, ["NAME"])],
        };

        var built = CrossTableMap.Build(Dbms.Oracle, Dbms.Tibero, table, "DST", NoJobTables);

        // 옮기지 않는 열(RID)·가상 열(V1)은 없고, IDENTITY 절과 원본 시퀀스 기본값은 없으며, RAW(3000) 은 BLOB 이다.
        // 옮기지 않는 열을 쓰는 CHECK·인덱스(CK_RID·IX_RID)는 만들지 않는다. 그 밖의 CHECK·인덱스는 그대로다.
        Assert.Equal(
        [
            "CREATE TABLE \"DST\".\"T\" (\"ID\" NUMBER(10) NOT NULL, \"NAME\" VARCHAR2(20 CHAR), \"BIGRAW\" BLOB,"
            + " CONSTRAINT \"PK_T\" PRIMARY KEY (\"ID\"), CONSTRAINT \"CK_NAME\" CHECK (LENGTH(NAME) > 0))",
            "CREATE INDEX \"DST\".\"IX_NAME\" ON \"DST\".\"T\" (\"NAME\")",
        ], built.Statements);
        Assert.Equal(["CK_RID"], built.OmittedConstraints);

        var notes = string.Join(" | ", built.Notes);
        Assert.Contains("RID", notes, StringComparison.Ordinal);
        Assert.Contains("V1", notes, StringComparison.Ordinal);
        Assert.Contains("IDENTITY 열 ID", notes, StringComparison.Ordinal);
        Assert.Contains("BIGRAW", notes, StringComparison.Ordinal);
        Assert.Contains("CK_RID", notes, StringComparison.Ordinal);
        Assert.Contains("IX_RID", notes, StringComparison.Ordinal);
    }

