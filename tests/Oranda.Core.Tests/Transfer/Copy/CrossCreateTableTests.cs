    [Fact]
    public void A_check_condition_is_read_for_dropped_columns_only_without_a_column_list_and_ignores_literals_and_quoted_case()
    {
        TableInfo Table(params ConstraintInfo[] checks) => new(new DbObjectRef("SRC", "T", "TABLE"),
        [
            new ColumnInfo("NAME", 1, "VARCHAR2") { Length = 20 },
            new ColumnInfo("RID", 2, "ROWID"),
        ])
        {
            Constraints = checks,
        };

        // 열 목록이 비었을 때만 조건 글을 본다: 글자가 들어 있어도 열 목록이 있으면 열 목록이 판정한다.
        var withColumns = CrossTableMap.MapTable(Dbms.Oracle, Dbms.Tibero, Table(
            new ConstraintInfo("CK_LISTED", ConstraintKind.Check, ["NAME"]) { Condition = "NAME <> 'x' AND RID IS NOT NULL" }));
        Assert.Empty(withColumns.OmittedConstraints);

        // 열 목록이 비면 글을 본다. 문자열 리터럴 안의 이름은 무시하고, 따옴표 이름은 대소문자를 구별하고, 따옴표 없는 이름은 구별하지 않는다.
        var bare = CrossTableMap.MapTable(Dbms.Oracle, Dbms.Tibero, Table(
            new ConstraintInfo("CK_LITERAL", ConstraintKind.Check, []) { Condition = "NAME <> 'RID'" },
            new ConstraintInfo("CK_ESCAPED", ConstraintKind.Check, []) { Condition = "NAME <> 'it''s RID'" },
            new ConstraintInfo("CK_QUOTED_OTHER_CASE", ConstraintKind.Check, []) { Condition = "\"rid\" IS NOT NULL" },
            new ConstraintInfo("CK_QUOTED", ConstraintKind.Check, []) { Condition = "\"RID\" IS NOT NULL" },
            new ConstraintInfo("CK_BARE_LOWER", ConstraintKind.Check, []) { Condition = "rid is not null" }));
        Assert.Equal(["CK_BARE_LOWER", "CK_QUOTED"], bare.OmittedConstraints.Order(StringComparer.Ordinal));
    }

