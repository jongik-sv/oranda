        var toOracle = new Fixture(Dbms.Tibero, Dbms.Oracle, Orders("SRC"), action: TargetAction.Recreate, create: false, targetHasTable: true,
            targetDialect: new PrecheckDialect(null));
        Assert.DoesNotContain((await toOracle.PrecheckAsync()).Items, i => i.Code == "RecreateBlocked");
    }

    [Fact]
    public async Task Cross_create_is_not_blocked_by_a_source_type_the_target_gets_converted_but_same_dbms_still_is()
    {
        // Tibero LONG 은 대량 쓰기 형식이 아니지만(IsSupported 거짓) 읽을 수 있고 Oracle 에는 CLOB 으로 만든다.
        var longTable = new TableInfo(new DbObjectRef("SRC", "ORDERS", "TABLE"),
        [
            new ColumnInfo("ID", 1, "NUMBER") { Precision = 10, Scale = 0, IsNullable = false },
            new ColumnInfo("L", 2, "LONG"),
        ])
        {
            Constraints = [new ConstraintInfo("PK_ORDERS", ConstraintKind.PrimaryKey, ["ID"])],
        };
        var cross = new Fixture(Dbms.Tibero, Dbms.Oracle, longTable, sourceCodec: new FakeCodec(unsupported: ["LONG"], readable: ["LONG"]));

        var report = await cross.PrecheckAsync();

        Assert.DoesNotContain(report.Items, i => i.Code == CopyCheckCodes.CreateBlocked);
        var item = Assert.Single(report.Items, i => i.Code == CopyCheckCodes.CreateTable);
        Assert.Contains("CLOB", item.Message, StringComparison.Ordinal);
        Assert.Contains(report.Preview, p => p.Sql.StartsWith("CREATE TABLE", StringComparison.Ordinal) && p.Sql.Contains("\"L\" CLOB", StringComparison.Ordinal));

        // 같은 DBMS 는 그대로 막는다.
        var same = new Fixture(Dbms.Oracle, Dbms.Oracle, longTable, sourceCodec: new FakeCodec(unsupported: ["LONG"], readable: []));
        var blocked = Assert.Single((await same.PrecheckAsync()).Items, i => i.Code == CopyCheckCodes.CreateBlocked);
        Assert.Contains("지원하지 않는 형식 열 L(LONG)", blocked.Message, StringComparison.Ordinal);
    }

    // ---- 실행기 == 미리 보기, IDENTITY 다음 값 ----

    [Fact]
    public async Task Cross_runner_sends_the_same_create_statements_the_precheck_previews_and_skips_the_identity_restart()
    {
        var f = new Fixture(Dbms.Oracle, Dbms.Tibero, IdentityOrders("SRC", cross: true));
        var report = await f.PrecheckAsync();
        Assert.False(report.HasErrors);

        var result = await f.RunAsync(report);

        var previewed = report.Preview.Where(p => p.Side == PreviewSide.Target && IsCreateText(p.Sql)).Select(p => p.Sql).ToList();
        var sent = f.Execution.Calls.Select(c => c.Statement.Text).Where(IsCreateText).ToList();
        Assert.NotEmpty(previewed);
        Assert.Equal(previewed, sent);
        Assert.DoesNotContain("RID", sent[0], StringComparison.Ordinal);
        Assert.DoesNotContain("V1", sent[0], StringComparison.Ordinal);
        Assert.DoesNotContain("IDENTITY", sent[0], StringComparison.Ordinal);
        Assert.DoesNotContain(f.Execution.Calls, c => c.Statement.Text.StartsWith("RESTART", StringComparison.Ordinal)); // 일반 열이라 맞출 다음 값이 없다

        var table = Assert.Single(result.Tables);
        Assert.Contains("원본과 달라지는 것", table.Message, StringComparison.Ordinal);
    }

