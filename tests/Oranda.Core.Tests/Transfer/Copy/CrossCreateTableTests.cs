    [Fact]
    public async Task Runner_leaves_out_a_server_named_job_fk_on_a_column_it_does_not_create_and_says_so()
    {
        var kept = ("ORDERS", "ALTER TABLE \"DST\".\"ORDERS\" ADD CONSTRAINT \"FK_KEPT\" FOREIGN KEY (\"NAME\") REFERENCES \"DST\".\"ORDERS\" (\"ID\")", (string?)"FK_KEPT");
        var onDropped = ("ORDERS", "ALTER TABLE \"DST\".\"ORDERS\" ADD FOREIGN KEY (\"RID\") REFERENCES \"DST\".\"ORDERS\" (\"ID\")", (string?)null);
