                                                  ExecutionOptions options, CancellationToken ct)
        {
            var isDml = columns.Count > 0;
            if (isDml && ReferenceEquals(s, fixture.Target))
            {
                _inserted += rows.Count;
            }

            return Task.FromResult(new BulkResult(ExecutionStatus.Succeeded, isDml ? rows.Count : 0));
        }
    }

