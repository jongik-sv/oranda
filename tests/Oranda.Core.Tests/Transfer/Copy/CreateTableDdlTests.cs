using Oranda.Core.Metadata;
using Oranda.Core.Transfer.Copy;
using Xunit;

namespace Oranda.Core.Tests.Transfer.Copy;

// 소유: 데이터 복사 Task 10. 「테이블 다시 만들기」 DDL 은 SELECT 권한만으로 읽는 메타데이터로 만든다(설계 6.2.3).
public class CreateTableDdlTests
{
    private static readonly HashSet<string> NoJob = new(StringComparer.Ordinal);

    private static TableInfo Table(string name, IReadOnlyList<ColumnInfo> columns,
                                   IReadOnlyList<ConstraintInfo>? constraints = null, IReadOnlyList<IndexInfo>? indexes = null,
                                   string? comment = null)
        => new(new DbObjectRef("CP_SRC", name, "TABLE"), columns)
        {
            Constraints = constraints ?? [],
            Indexes = indexes ?? [],
            Comment = comment,
        };

    [Fact]
    public void Builds_columns_with_types_defaults_and_not_null()
    {
        var t = Table("ORDERS",
        [
            new ColumnInfo("ID", 1, "NUMBER") { Precision = 10, Scale = 0, IsNullable = false },
            new ColumnInfo("AMT", 2, "NUMBER") { Precision = 12, Scale = 2 },
            new ColumnInfo("QTY", 3, "NUMBER") { Scale = 0 },
            new ColumnInfo("NAME", 4, "VARCHAR2") { Length = 50, DefaultValue = "'NONE'" },
            new ColumnInfo("CODE", 5, "NCHAR") { Length = 3 },
            new ColumnInfo("RW", 6, "RAW") { Length = 16 },
            new ColumnInfo("TS", 7, "TIMESTAMP(6) WITH TIME ZONE"),
            new ColumnInfo("REG_DT", 8, "DATE") { DefaultValue = "SYSDATE", IsNullable = false },
            new ColumnInfo("SEQ_ID", 9, "NUMBER") { IsIdentity = true, DefaultValue = "\"CP_SRC\".\"ISEQ$$_1\".nextval", IsNullable = false },
            new ColumnInfo("TOTAL", 10, "NUMBER") { IsVirtual = true, DefaultValue = "\"AMT\"*2" },
            new ColumnInfo("HID", 11, "VARCHAR2") { Length = 5, IsInvisible = true },
        ]);

        var ddl = CreateTableDdl.Build(t, "CP_DST", NoJob);

        Assert.Equal(
            "CREATE TABLE \"CP_DST\".\"ORDERS\" (\"ID\" NUMBER(10) NOT NULL, \"AMT\" NUMBER(12,2), \"QTY\" NUMBER(*,0),"
            + " \"NAME\" VARCHAR2(50 CHAR) DEFAULT 'NONE', \"CODE\" NCHAR(3), \"RW\" RAW(16), \"TS\" TIMESTAMP(6) WITH TIME ZONE,"
            + " \"REG_DT\" DATE DEFAULT SYSDATE NOT NULL, \"SEQ_ID\" NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,"
            + " \"TOTAL\" NUMBER GENERATED ALWAYS AS (\"AMT\"*2) VIRTUAL, \"HID\" VARCHAR2(5 CHAR) INVISIBLE)",
            Assert.Single(ddl));
        Assert.DoesNotContain("ISEQ$$", ddl[0], StringComparison.Ordinal);
    }

    [Fact]
    public void Builds_pk_uk_check_and_in_job_fk_only()
    {
        var t = Table("ORDER_ITEM",
        [
            new ColumnInfo("ID", 1, "NUMBER") { IsNullable = false },
            new ColumnInfo("ORDER_ID", 2, "NUMBER"),
            new ColumnInfo("CUST_ID", 3, "NUMBER"),
            new ColumnInfo("SKU", 4, "VARCHAR2") { Length = 20 },
        ],
        [
            new ConstraintInfo("PK_ORDER_ITEM", ConstraintKind.PrimaryKey, ["ID"]),
            new ConstraintInfo("SYS_C0012345", ConstraintKind.Unique, ["SKU"]),
            new ConstraintInfo("CK_QTY", ConstraintKind.Check, ["ID"]) { Condition = "\"ID\" > 0" },
            new ConstraintInfo("FK_ITEM_ORDER", ConstraintKind.ForeignKey, ["ORDER_ID"]) { ReferencedTable = new DbObjectRef("CP_SRC", "ORDERS", "TABLE") },
            new ConstraintInfo("FK_ITEM_CUST", ConstraintKind.ForeignKey, ["CUST_ID"]) { ReferencedTable = new DbObjectRef("CP_SRC", "CUSTOMER", "TABLE") },
        ]);

        var ddl = CreateTableDdl.Build(t, "CP_DST", new HashSet<string>(["ORDERS", "ORDER_ITEM"], StringComparer.Ordinal));

        Assert.Equal(2, ddl.Count);
        Assert.EndsWith(
            "\"SKU\" VARCHAR2(20 CHAR), CONSTRAINT \"PK_ORDER_ITEM\" PRIMARY KEY (\"ID\"), UNIQUE (\"SKU\"), CONSTRAINT \"CK_QTY\" CHECK (\"ID\" > 0))",
            ddl[0], StringComparison.Ordinal);
        Assert.Equal(
            "ALTER TABLE \"CP_DST\".\"ORDER_ITEM\" ADD CONSTRAINT \"FK_ITEM_ORDER\" FOREIGN KEY (\"ORDER_ID\") REFERENCES \"CP_DST\".\"ORDERS\"",
            ddl[1]);
        Assert.DoesNotContain(ddl, s => s.Contains("CUSTOMER", StringComparison.Ordinal));
    }

    [Fact]
    public void Skips_constraint_backed_indexes_and_adds_comments()
    {
        var t = Table("ORDERS",
        [
            new ColumnInfo("ID", 1, "NUMBER") { IsNullable = false, Comment = "주문 번호" },
            new ColumnInfo("ORDER_DT", 2, "DATE"),
            new ColumnInfo("NAME", 3, "VARCHAR2") { Length = 30 },
        ],
        [new ConstraintInfo("PK_ORDERS", ConstraintKind.PrimaryKey, ["ID"])],
        [
            new IndexInfo("PK_ORDERS", true, ["ID"]),
            new IndexInfo("IX_ORDERS_DT", false, ["ORDER_DT", "ID"]) { IndexType = "NORMAL" },
            new IndexInfo("IX_ORDERS_UPPER", false, ["SYS_NC00004$"]) { IndexType = "FUNCTION-BASED NORMAL" },
            new IndexInfo("SYS_IL0000012345C00003$$", true, ["NAME"]) { IndexType = "LOB" },
        ],
        comment: "고객's 주문");

        var ddl = CreateTableDdl.Build(t, "CP_DST", NoJob);

        Assert.Equal(
        [
            "CREATE INDEX \"CP_DST\".\"IX_ORDERS_DT\" ON \"CP_DST\".\"ORDERS\" (\"ORDER_DT\", \"ID\")",
            "COMMENT ON TABLE \"CP_DST\".\"ORDERS\" IS '고객''s 주문'",
            "COMMENT ON COLUMN \"CP_DST\".\"ORDERS\".\"ID\" IS '주문 번호'",
        ], ddl.Skip(1));
    }

    [Fact]
    public void Never_emits_tablespace_partition_or_compress()
    {
        var t = Table("BIG",
            [new ColumnInfo("ID", 1, "NUMBER"), new ColumnInfo("DOC", 2, "CLOB")],
            [new ConstraintInfo("PK_BIG", ConstraintKind.PrimaryKey, ["ID"])],
            [new IndexInfo("IX_BIG", false, ["ID", "DOC"])]);

        var all = string.Join("\n", CreateTableDdl.Build(t, "CP_DST", NoJob));

        foreach (var word in new[] { "TABLESPACE", "PARTITION", "COMPRESS", "STORAGE", "PCTFREE", "LOGGING", "TRIGGER", "GRANT", "PURGE" })
        {
            Assert.DoesNotContain(word, all, StringComparison.OrdinalIgnoreCase);
        }
    }

    [Fact]
    public void Invisible_virtual_column_and_source_owner_in_expressions()
    {
        var t = Table("ORDERS",
        [
            new ColumnInfo("ID", 1, "NUMBER") { DefaultValue = "\"CP_SRC\".\"ORD_SEQ\".\"NEXTVAL\"", IsNullable = false },
            new ColumnInfo("AMT", 2, "NUMBER"),
            new ColumnInfo("TAX", 3, "NUMBER") { IsVirtual = true, IsInvisible = true, DefaultValue = "\"CP_SRC\".\"TAX_OF\"(\"AMT\")" },
        ]);

        var create = CreateTableDdl.Build(t, "CP_DST", NoJob)[0];

        // INVISIBLE 은 생성 절 앞이다. 식 안의 원본 소유자는 대상 소유자로 바뀐다.
        Assert.Equal(
            "CREATE TABLE \"CP_DST\".\"ORDERS\" (\"ID\" NUMBER DEFAULT \"CP_DST\".\"ORD_SEQ\".\"NEXTVAL\" NOT NULL, \"AMT\" NUMBER,"
            + " \"TAX\" NUMBER INVISIBLE GENERATED ALWAYS AS (\"CP_DST\".\"TAX_OF\"(\"AMT\")) VIRTUAL)",
            create);
        Assert.True(CreateTableDdl.ReferencesOwner(t.Columns[0].DefaultValue, "CP_SRC"));
        Assert.False(CreateTableDdl.ReferencesOwner(t.Columns[1].DefaultValue, "CP_SRC"));
        Assert.Equal(["ORD_SEQ"], CreateTableDdl.ReferencedObjects(t.Columns[0].DefaultValue, "CP_SRC"));
        Assert.Equal(["TAX_OF"], CreateTableDdl.ReferencedObjects(t.Columns[2].DefaultValue, "CP_SRC"));
    }

    [Fact]
    public void Named_objects_lists_names_create_will_use()
    {
        var t = Table("ORDERS",
            [new ColumnInfo("ID", 1, "NUMBER"), new ColumnInfo("CODE", 2, "VARCHAR2") { Length = 5 }, new ColumnInfo("NAME", 3, "VARCHAR2") { Length = 5 }],
            [
                new ConstraintInfo("ORDERS_PK", ConstraintKind.PrimaryKey, ["ID"]),
                new ConstraintInfo("SYS_C001", ConstraintKind.Unique, ["CODE"]),
                new ConstraintInfo("ORDERS_CK", ConstraintKind.Check, ["ID"]) { Condition = "ID > 0" },
                new ConstraintInfo("ORDERS_FK", ConstraintKind.ForeignKey, ["ID"]) { ReferencedTable = new DbObjectRef("CP_SRC", "P", "TABLE") },
            ],
            [new IndexInfo("ORDERS_PK", true, ["ID"]), new IndexInfo("ORDERS_NAME_IX", false, ["NAME"]), new IndexInfo("SYS_C001", true, ["CODE"])]);

        var (constraints, indexes) = CreateTableDdl.NamedObjects(t);

        // 서버 이름(SYS_)·FK 는 빼고, PK 는 제약과 같은 이름의 인덱스도 만든다.
        Assert.Equal(["ORDERS_PK", "ORDERS_CK"], constraints);
        Assert.Equal(["ORDERS_PK", "ORDERS_NAME_IX"], indexes);
    }

    /// <summary>Oracle 사전이 내는 형식 이름의 글은 그대로다(TB4 에서 Tibero 갈래를 더할 때 고정).</summary>
    [Theory]
    [InlineData("VARCHAR2", 50, "VARCHAR2(50 CHAR)")]
    [InlineData("CHAR", 3, "CHAR(3 CHAR)")]
    [InlineData("NVARCHAR2", 20, "NVARCHAR2(20)")]
    [InlineData("NCHAR", 2, "NCHAR(2)")]
    [InlineData("RAW", 16, "RAW(16)")]
    [InlineData("varchar2", 7, "VARCHAR2(7 CHAR)")]
    public void Oracle_type_names_keep_their_text(string type, int length, string expected)
    {
        Assert.Equal(expected, CreateTableDdl.TypeText(new ColumnInfo("C", 1, type) { Length = length }));
    }

    /// <summary>Tibero 사전은 VARCHAR2·NVARCHAR2 열을 VARCHAR·NVARCHAR 로 낸다: 길이를 붙여 Oracle 꼴로 쓴다(없으면 길이 없는 「VARCHAR」 → TBR-7001, win144 #77).</summary>
    [Theory]
    [InlineData("VARCHAR", 4000, "VARCHAR2(4000 CHAR)")]
    [InlineData("NVARCHAR", 30, "NVARCHAR2(30)")]
    [InlineData("varchar", 5, "VARCHAR2(5 CHAR)")]
    public void Tibero_dictionary_varchar_names_get_their_length(string type, int length, string expected)
    {
        Assert.Equal(expected, CreateTableDdl.TypeText(new ColumnInfo("C", 1, type) { Length = length }));
    }
}
